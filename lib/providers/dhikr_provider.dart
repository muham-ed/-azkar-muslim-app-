  List<DhikrCategory> get categories => _categories;

  DhikrProvider() {
    _loadState();
  }

  void incrementDhikr(String categoryName, String dhikrId) async {
    try {
      final category = _categories.firstWhere((cat) => cat.name == categoryName);
      final dhikr = category.dhikrs.firstWhere((d) => d.id == dhikrId);

      if (dhikr.currentCount < dhikr.targetCount) {
        dhikr.increment();
        if (await Vibration.hasVibrator() == true) {
          Vibration.vibrate(duration: 45);
        }
        notifyListeners();
        _saveDhikrState(dhikr.id, dhikr.currentCount);
      }
    } catch (e) {
      debugPrint('Error incrementing dhikr: $e');
    }
  }

  void resetDhikr(String categoryName, String dhikrId) {
    try {
      final category = _categories.firstWhere((cat) => cat.name == categoryName);
      final dhikr = category.dhikrs.firstWhere((d) => d.id == dhikrId);
      dhikr.reset();
      notifyListeners();
      _saveDhikrState(dhikr.id, 0);
    } catch (e) {
      debugPrint('Error resetting dhikr: $e');
    }
  }

  void resetCategory(String categoryName) {
    try {
      final category = _categories.firstWhere((cat) => cat.name == categoryName);
      for (var dhikr in category.dhikrs) {
        dhikr.reset();
        _saveDhikrState(dhikr.id, 0);
      }
      notifyListeners();
    } catch (e) {
      debugPrint('Error resetting category: $e');
    }
  }

  Future<void> _saveDhikrState(String dhikrId, int count) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setInt('dhikr_count_$dhikrId', count);
      final todayStr = DateTime.now().toIso8601String().substring(0, 10);
      await prefs.setString(_dateKey, todayStr);
    } catch (e) {
      debugPrint('Error saving dhikr state: $e');
    }
  }

  Future<void> _loadState() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedDate = prefs.getString(_dateKey);
      final todayStr = DateTime.now().toIso8601String().substring(0, 10);

      if (savedDate != null && savedDate != todayStr) {
        for (var cat in _categories) {
          for (var d in cat.dhikrs) {
            d.reset();
            await prefs.setInt('dhikr_count_${d.id}', 0);
          }
        }
        await prefs.setString(_dateKey, todayStr);
      } else {
        for (var cat in _categories) {
          for (var d in cat.dhikrs) {
            final savedCount = prefs.getInt('dhikr_count_${d.id}') ?? 0;
            d.currentCount = savedCount;
          }
        }
      }
      notifyListeners();
    } catch (e) {
      debugPrint('Error loading dhikr state: $e');
    }
  }
